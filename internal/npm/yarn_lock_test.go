package npm

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/Xsamsx/SBOMber/internal/deps"
)

func TestEnrichFromYarnLock(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	lockfile := `# yarn lockfile v8

__metadata:
  version: 8

"chalk@npm:^5.0.0":
  version: 5.6.2
  resolution: "chalk@npm:5.6.2"
  dependencies:
    ansi-styles: "npm:^4.3.0"

"ansi-styles@npm:^4.3.0":
  version: 4.3.0
  resolution: "ansi-styles@npm:4.3.0"

"vite@npm:^5.0.0":
  version: 5.4.0
  resolution: "vite@npm:5.4.0"
  dependencies:
    esbuild: "npm:^0.21.0"

"esbuild@npm:^0.21.0":
  version: 0.21.5
  resolution: "esbuild@npm:0.21.5"
`
	if err := os.WriteFile(filepath.Join(root, "yarn.lock"), []byte(lockfile), 0o644); err != nil {
		t.Fatalf("write yarn.lock: %v", err)
	}

	summary := deps.Summary{
		Direct: []deps.Dependency{
			{Name: "chalk", Version: "^5.0.0", Scope: deps.ScopeRuntime},
			{Name: "vite", Version: "^5.0.0", Scope: deps.ScopeDev},
		},
	}

	enriched, err := EnrichFromYarnLock(root, summary)
	if err != nil {
		t.Fatalf("EnrichFromYarnLock returned error: %v", err)
	}

	if enriched.TransitiveCount() != 2 {
		t.Fatalf("expected 2 transitive dependencies, got %d", enriched.TransitiveCount())
	}

	if enriched.Transitive[0].Name != "ansi-styles" || enriched.Transitive[1].Name != "esbuild" {
		t.Fatalf("unexpected transitive dependencies: %#v", enriched.Transitive)
	}
}

// Yarn v1 (classic) lockfiles use `version "x"` and space-separated
// dependency lines; direct dependencies take the version yarn resolved.
func TestEnrichFromYarnLockV1(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	lockfile := `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@types/body-parser@*":
  version "1.19.0"
  resolved "https://registry.yarnpkg.com/@types/body-parser/-/body-parser-1.19.0.tgz"
  dependencies:
    "@types/connect" "*"

"@types/connect@*":
  version "3.4.34"

node-serialize@^0.0.4:
  version "0.0.4"
  resolved "https://registry.yarnpkg.com/node-serialize/-/node-serialize-0.0.4.tgz"

express@^4.17.1:
  version "4.17.1"
  dependencies:
    accepts "~1.3.7"
    "@types/body-parser" "*"

accepts@~1.3.7:
  version "1.3.7"
`
	if err := os.WriteFile(filepath.Join(root, "yarn.lock"), []byte(lockfile), 0o644); err != nil {
		t.Fatalf("write yarn.lock: %v", err)
	}

	summary := deps.Summary{Direct: []deps.Dependency{
		{Name: "express", Version: "^4.17.1", Scope: deps.ScopeRuntime},
		{Name: "node-serialize", Version: "^0.0.4", Scope: deps.ScopeRuntime},
	}}
	enriched, err := EnrichFromYarnLock(root, summary)
	if err != nil {
		t.Fatalf("EnrichFromYarnLock returned error: %v", err)
	}

	if enriched.Direct[0].Version != "4.17.1" || enriched.Direct[1].Version != "0.0.4" {
		t.Fatalf("direct versions = %q, %q; want the resolved 4.17.1 and 0.0.4", enriched.Direct[0].Version, enriched.Direct[1].Version)
	}
	if got := enriched.Direct[0].Children; len(got) != 2 || got[0] != "accepts" || got[1] != "@types/body-parser" {
		t.Fatalf("express children = %v", got)
	}
	versions := map[string]string{}
	for _, dep := range enriched.Transitive {
		versions[dep.Name] = dep.Version
	}
	if versions["accepts"] != "1.3.7" || versions["@types/connect"] != "3.4.34" || versions["@types/body-parser"] != "1.19.0" {
		t.Fatalf("transitive = %v", versions)
	}
}
